// Public list of product photos/videos uploaded through the admin page (stored on Cloudinary).
// Needs Netlify env vars: CLOUDINARY_CLOUD_NAME, CLOUDINARY_API_KEY, CLOUDINARY_API_SECRET

const TAG = "sardar";

export default async (req) => {
  const { CLOUDINARY_CLOUD_NAME: cloud, CLOUDINARY_API_KEY: key, CLOUDINARY_API_SECRET: secret } = process.env;
  if (!cloud || !key || !secret) return Response.json({ items: [], error: "Cloudinary not configured" }, { status: 200 });

  try {
    const items = [];
    let cursor;
    for (let i = 0; i < 5; i++) {
      const res = await fetch(`https://api.cloudinary.com/v1_1/${cloud}/resources/search`, {
        method: "POST",
        headers: { "Content-Type": "application/json", Authorization: "Basic " + btoa(`${key}:${secret}`) },
        body: JSON.stringify({
          expression: `tags=${TAG}`,
          with_field: ["context", "tags"],
          sort_by: [{ created_at: "desc" }],
          max_results: 500,
          ...(cursor ? { next_cursor: cursor } : {})
        })
      });
      const j = await res.json();
      if (!res.ok || j.error) throw new Error(j.error?.message || `Cloudinary ${res.status}`);
      for (const r of j.resources || []) items.push(toItem(r, cloud));
      cursor = j.next_cursor;
      if (!cursor) break;
    }
    return Response.json({ items }, {
      headers: { "Cache-Control": "public, max-age=0", "Netlify-CDN-Cache-Control": "public, s-maxage=60, stale-while-revalidate=120" }
    });
  } catch (e) {
    return Response.json({ items: [], error: e.message }, { status: 502 });
  }
};

function ctx(r) {
  // Search API returns context either flat ({code}) or nested ({custom:{code}})
  const c = r.context || {};
  return c.custom || c;
}

function toItem(r, cloud) {
  const c = ctx(r);
  const base = `https://res.cloudinary.com/${cloud}`;
  const isVideo = r.resource_type === "video";
  const id = r.public_id;
  return {
    id: "cld_" + id,
    publicId: id,
    resourceType: r.resource_type,
    type: isVideo ? "video" : "image",
    // Small, phone-friendly versions generated by Cloudinary on the fly
    src: isVideo ? `${base}/video/upload/q_auto,w_720,c_limit/${id}.mp4` : `${base}/image/upload/f_auto,q_auto,w_1080,c_limit/${id}`,
    thumbnail: isVideo ? `${base}/video/upload/so_0,q_auto,w_480,c_limit/${id}.jpg` : `${base}/image/upload/f_auto,q_auto,w_480,c_limit/${id}`,
    preview: isVideo ? `${base}/video/upload/q_auto:low,w_480,c_limit,ac_none/${id}.mp4` : "",
    code: c.code || "",
    caption: c.code || "",
    cat: c.cat || "",
    permalink: "",
    timestamp: r.created_at
  };
}

